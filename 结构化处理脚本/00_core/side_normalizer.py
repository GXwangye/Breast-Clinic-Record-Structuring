_RE_DUP_PAREN = re.compile(r"^(.*)[（(]\s*(%s)\s*[)）]$" % _SITE_PURE)

def drop_dup_site_paren(base):
    m = _RE_DUP_PAREN.match(base or "")
    if m and SITE_FAM[m.group(2)] in m.group(1):
        return m.group(1).strip(), True
    return base, False

class _Span(object):
    __slots__ = ("_s", "_e", "_g")

    def __init__(self, s, e, g):
        self._s, self._e, self._g = s, e, g

    def start(self):
        return self._s

    def end(self):
        return self._e

    def group(self, i=0):
        return self._g

def norm_side(raw):
    if raw in ("双侧", "两侧", "双", "两"):
        return "双"
    if raw in ("左侧", "左"):
        return "左"
    if raw in ("右侧", "右"):
        return "右"
    if raw == "单侧":
        return "单侧"
    return raw

def strip_term(term):
    t = (term or "").strip()
    notes = []
    side = None

    # ⓪ 假侧别词头：整条不剥（左甲状腺素 ≠ 左侧甲状腺素）
    if t.startswith(PROTECT):
        return "未指明", t, "不剥·假侧别词头", "药物构型词头"

    # ① 尾部括号侧别最明确，优先采信
    m = TAIL_SIDE.search(t)
    if m:
        side = norm_side(m.group(1))
        t = (t[:m.start()] + t[m.end():]).strip()

    # ② 词内侧别（任意位置，但必须紧邻宿主词）
    ms = list(ANY_SIDE.finditer(t))
    # ②b 句读式：侧别标记后紧跟分隔符而非部位词
    if not ms:
        ms = list(SIDE_BEFORE_SEP.finditer(t))
    # ②c 括号起始式：只取括号内的侧别字，左括号保留
    if not ms:
        ms = [_Span(m.end() - len(m.group(1)), m.end(), m.group(1))
              for m in PAREN_HEAD.finditer(t)]
    # ②d 侧别 + 数字（「右侧10点钟」「左侧9-10点钟」）
    if not ms:
        ms = list(SIDE_NUM.finditer(t))
    if not ms and side is None:
        rel = REL_SIDE.search(t)
        if rel:
            return "未指明", (term or "").strip(), "关系型侧别·待人工", \
                   "出现「%s」，侧别须人工判定" % rel.group(1)
        # 无侧别也做一次去冗余括注：「乳腺癌术后(乳房)」→「乳腺癌术后」。
        # ⚠ 此分支**不做部位补全**（补全会改动无侧别实体的标准名，超出侧别职责）。
        b0, chg = drop_dup_site_paren((term or "").strip())
        return "未指明", b0, ("去冗余部位括注" if chg else "无侧别·未改"), ""
    if ms:
        found = [norm_side(m.group(0)) for m in ms]
        if side is None:
            side = found[0]
        elif len(ms) > 1:
            notes.append("冗余侧别%d处" % len(ms))
        # 多侧别并存：文本里出现 >1 个**不同**侧别，单一 side 无法表达 → 转人工
        if len({x for x in found if x}) > 1:
            notes.append("多侧别并存（%s），待人工裁定" % "/".join(
                dict.fromkeys(found)))
        for mm in reversed(ms):
            t = t[:mm.start()] + t[mm.end():]
    if REL_SIDE.search(t):
        notes.append("关系型侧别待人工")

    # ③ 剥后补全
    base = re.sub(r"\s+", "", t)
    # 清理剥离留下的悬空分隔符：「(，T2N0M0…)」→「(T2N0M0…)」、「(，)」→「」
    base = re.sub(r"[（(]\s*[，,、]+\s*", "(", base)
    base = re.sub(r"\s*[，,、]+\s*[)）]", ")", base)
    base = re.sub(r"[（(]\s*[)）]", "", base)
    action = "纯剥离"
    # ⚠ 补全规则**只作用于括注之前的主干**：括注内是限定语（如「乳头炎(左乳乳头赘生物)」），
    #   对括注内补全会把「乳乳头赘生物」错改成「乳房乳头赘生物」。
    _hi = re.search(r"[（(]", base)
    head, tail = (base[:_hi.start()], base[_hi.start():]) if _hi else (base, "")
    if not head:
        head, action = "乳房", "剥空→补基名"
    elif head.startswith("乳癌"):
        head, action = "乳腺癌" + head[2:], "补全部位"
    elif head.startswith("乳") and head[1:2] not in HEAD_OK:
        head, action = "乳房" + head[1:], "补全部位"
    elif head.startswith("腋") and not head.startswith("腋窝"):
        head, action = "腋窝" + head[1:], "补全部位"
    if re.search(GUARD + r"乳癌", head):
        head, action = re.sub(GUARD + r"乳癌", "乳腺癌", head), "补全部位"
    if re.search(GUARD + r"乳(?!腺|房|癌|头|晕|管)", head):
        head, action = re.sub(GUARD + r"乳(?!腺|房|癌|头|晕|管)", "乳房", head), "补全部位"
    base = head + tail
    # ③b 去冗余部位括注：「乳房结节(左乳)」→ 剥「左」后成「乳房结节(乳)」，
    #     括注里只剩主干已含的同一部位 → 删除括注。不同部位（乳腺肿块(腋窝)）不删。
    base, _chg = drop_dup_site_paren(base)
    if _chg:
        action = "去冗余部位括注"
    if base in CTX_FILL:
        base, action = CTX_FILL[base], "补全部位（依病历域推定）"
        notes.append("补入部位需人工确认")

    # ④ 质量判定
    if not base:
        action, notes = "碎片待修", notes + ["剥离后为空"]
    elif base in BARE_MOD:
        notes.append("剥后缺部位，待人工")
    if (base.startswith("乳房") and base.count("乳房") > 1) or \
       (base.startswith("乳腺") and base.count("乳腺") > 1) or base.count("乳") >= 3:
        notes.append("部位词重复/粘连，待人工")
    if len(base) > 18 or re.search(r"[和与及的为是]$", base):
        notes.append("疑似原文截断，待人工")
    if base and not re.search(r"乳|腋|胸壁", base):
        if any(o in base for o in ORGAN):
            notes.append("跨域实体（非乳腺域）")
        elif base not in BARE_MOD:
            notes.append("需人工确认域归属")
    return side, base, action, "; ".join(dict.fromkeys(notes))

